def canonical_pack_hash():
    """Bind a deterministic version and exact card content without side effects."""
    body = json.dumps({"version": PACK_VERSION, "cards": BEAUTYOS_KNOWLEDGE_PACK},
                      ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(body).hexdigest()
